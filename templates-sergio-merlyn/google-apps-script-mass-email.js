/**
 * ═══════════════════════════════════════════════════════════════════════════
 * Sergio & Merilyn — Wedding Mass Email Sender
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * HOW IT WORKS:
 *   • Reads guest rows from the "Invitados" tab
 *   • Skips any row that already has "Enviado ✓" in the Status column
 *   • Sends a personalized HTML email with the guest's unique invitation link
 *   • Marks each sent row as "Enviado ✓" + timestamp
 *
 * FUNCTIONS YOU CAN RUN:
 *   ▶ sendTestBatch()       — Sends to the first 5 UNSENT rows only (for testing)
 *   ▶ sendAllInvitations()  — Sends to up to 90 UNSENT rows per run
 *                             (run daily until all are sent)
 *
 * ADDING NEW GUESTS LATER:
 *   Just add new rows to the "Invitados" tab. They won't have "Enviado ✓"
 *   in the Status column, so the next run of sendAllInvitations() or
 *   sendTestBatch() will pick them up automatically.
 *
 * SPREADSHEET TAB: "Invitados"
 *   Column A: No.        (row number)
 *   Column B: Nombre     (e.g. "Familia Flores Castro")
 *   Column C: Email      (e.g. "flores@gmail.com")
 *   Column D: Invitados  (e.g. 4)
 *   Column E: Mesa       (e.g. 12, or leave blank)
 *   Column F: URL        (auto-generated by formula — or leave empty for fallback)
 *   Column G: Status     (leave empty — script fills this)
 */

// ══════════════════════════════════════════════════════════════════════════
// CONFIG
// ══════════════════════════════════════════════════════════════════════════
var CONFIG = {
  SHEET_NAME: "Invitados",
  SITE_URL: "https://bodacervantessoto.upbox.xyz/",
  SENDER_NAME: "Sergio & Merilyn",
  REPLY_TO: "sergioymerilyn@gmail.com",
  SUBJECT: "Sergio & Merilyn — Estás invitado a nuestra boda 💍",
  MAX_PER_RUN: 90,    // safety margin under Gmail's 100/day limit
  TEST_BATCH: 5      // how many to send in test mode
};

// ══════════════════════════════════════════════════════════════════════════
// PUBLIC FUNCTIONS — Run these from the Apps Script editor (▶ button)
// ══════════════════════════════════════════════════════════════════════════

/**
 * 🧪 TEST — Sends to the first 5 unsent rows only.
 * Use this to verify the email looks correct before doing a full send.
 */
function sendTestBatch() {
  _sendEmails(CONFIG.TEST_BATCH);
}

/**
 * 🚀 FULL SEND — Sends to up to 90 unsent rows.
 * Run this daily until all guests have "Enviado ✓" in their Status column.
 * Safe to run multiple times — it never re-sends to the same person.
 */
function sendAllInvitations() {
  _sendEmails(CONFIG.MAX_PER_RUN);
}

// ══════════════════════════════════════════════════════════════════════════
// INTERNAL — Email sending engine
// ══════════════════════════════════════════════════════════════════════════

function _sendEmails(limit) {
  var ss = SpreadsheetApp.getActiveSpreadsheet();
  var sheet = ss.getSheetByName(CONFIG.SHEET_NAME);
  if (!sheet) {
    SpreadsheetApp.getUi().alert('❌ No se encontró la pestaña "' + CONFIG.SHEET_NAME + '"');
    return;
  }

  var data = sheet.getDataRange().getValues();
  var sent = 0;
  var skipped = 0;
  var errors = 0;

  // Start from row 2 (skip header)
  for (var i = 1; i < data.length; i++) {
    if (sent >= limit) break;

    var nombre = String(data[i][1] || "").trim();
    var email = String(data[i][2] || "").trim();
    var invitados = String(data[i][3] || "").trim();
    var mesa = String(data[i][4] || "").trim();
    var url = String(data[i][5] || "").trim();
    var status = String(data[i][6] || "").trim();

    // Skip if already sent or missing data
    if (status.indexOf("Enviado") !== -1) { skipped++; continue; }
    if (!email || !nombre) continue;

    // Fallback: build URL if the formula column is empty
    if (!url) {
      url = CONFIG.SITE_URL
        + "?nombre=" + encodeURIComponent(nombre)
        + "&invitados=" + encodeURIComponent(invitados || "2")
        + (mesa ? "&mesa=" + encodeURIComponent(mesa) : "")
        + "&show=yes";
    }

    try {
      var html = _buildEmailHTML(nombre, url);
      GmailApp.sendEmail(email, CONFIG.SUBJECT, "Abre este correo en un cliente que soporte HTML.", {
        htmlBody: html,
        name: CONFIG.SENDER_NAME,
        replyTo: CONFIG.REPLY_TO
      });
      // Mark as sent (column G = 7)
      sheet.getRange(i + 1, 7).setValue("Enviado ✓ — " + new Date().toLocaleString("es-GT"));
      sent++;
    } catch (err) {
      sheet.getRange(i + 1, 7).setValue("Error — " + err.toString());
      errors++;
    }
  }

  // Summary popup
  var msg = "✅ Enviados: " + sent + "\n"
    + "⏭ Ya enviados (omitidos): " + skipped + "\n"
    + "❌ Errores: " + errors + "\n\n"
    + "Pendientes: " + (data.length - 1 - sent - skipped - errors);
  SpreadsheetApp.getUi().alert("Resumen de envío", msg, SpreadsheetApp.getUi().ButtonSet.OK);
}

